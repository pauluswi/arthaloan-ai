package com.pswied.core.arthaloan.demo;

import org.springframework.ai.chat.client.ChatClient;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.time.OffsetDateTime;
import java.util.List;

@Service
@ConditionalOnProperty(name = "spring.ai.model.chat", havingValue = "ollama")
public class OllamaAssistantService {

    private static final String SYSTEM_PROMPT = """
            You are the local ArthaLoan AI demo assistant. Use only the provided portfolioAnalytics and
            collectionWorklist tools for financial values or portfolio facts. Call the relevant tool before
            answering those questions. Never invent or estimate figures, accounts, policy rules, or trends.
            Explain the relevant evidence briefly. State when the tools do not contain enough information.
            Collection suggestions are only for human review; do not claim that a borrower was contacted or
            that any action was taken. Do not approve or reject borrowers, and do not provide account-level
            personal data. This application uses synthetic demo data only.
            """;

    private static final List<String> AVAILABLE_TOOLS =
            List.of("portfolioAnalytics", "collectionWorklist");

    private final ChatClient chatClient;
    private final OllamaAssistantTools tools;
    private final String modelName;
    private final String baseUrl;

    public OllamaAssistantService(
            ChatClient.Builder chatClientBuilder,
            OllamaAssistantTools tools,
            @Value("${spring.ai.ollama.chat.options.model}") String modelName,
            @Value("${spring.ai.ollama.base-url}") String baseUrl) {
        this.chatClient = chatClientBuilder.build();
        this.tools = tools;
        this.modelName = modelName;
        this.baseUrl = baseUrl;
    }

    public OllamaAssistantStatus status() {
        return new OllamaAssistantStatus(true, modelName, baseUrl);
    }

    public OllamaAssistantResponse answer(OllamaAssistantRequest request) {
        if (request == null || request.question() == null || request.question().isBlank()) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "question is required.");
        }
        String question = request.question().strip();
        if (question.length() > 1000) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "question must not exceed 1000 characters.");
        }
        String answer = chatClient.prompt()
                .system(SYSTEM_PROMPT)
                .user(question)
                .tools(tools)
                .call()
                .content();
        if (answer == null || answer.isBlank()) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_GATEWAY,
                    "The local model returned an empty answer. Check the Ollama model and try again.");
        }
        return new OllamaAssistantResponse(
                "LOCAL_OLLAMA",
                modelName,
                answer.strip(),
                OffsetDateTime.now(),
                "Answer generated by local Ollama; portfolio figures are available only through the listed tools.",
                AVAILABLE_TOOLS);
    }
}
